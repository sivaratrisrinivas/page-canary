//! Replay harness: real before/after pairs plus labeled synthetic mutations.
use crate::detect::{compare, Report, Thresholds, Verdict};
use crate::mutate::{apply, BENIGN, BREAKING};
use crate::profile::{profile, Field};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;

#[derive(Deserialize, Clone)]
pub struct Config { pub key: String, pub url: String, pub fields: Vec<Field> }
#[derive(Deserialize)]
struct Pair { config: String, before: String, after: String, label: String, note: String }
#[derive(Deserialize)]
struct Base { config: String, file: String }
#[derive(Deserialize)]
struct Fixtures { configs: Vec<Config>, real: Vec<Pair>, synthetic_bases: Vec<Base>, seeds: Vec<u64> }

#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Case {
    pub set: String, pub config: String, pub before: String, pub after: String, pub mutation: String,
    pub label_break: bool, pub note: String, pub report: Report,
}
#[derive(Serialize, Deserialize, Clone, Debug, Default, PartialEq)]
pub struct Score { pub tp: usize, pub fp: usize, pub fn_: usize, pub tn: usize }
impl Score {
    pub fn add(&mut self, label: bool, pred: bool) { match (label, pred) { (true, true) => self.tp += 1, (false, true) => self.fp += 1, (true, false) => self.fn_ += 1, _ => self.tn += 1 } }
    pub fn precision(&self) -> f64 { if self.tp + self.fp == 0 { 1.0 } else { self.tp as f64 / (self.tp + self.fp) as f64 } }
    pub fn recall(&self) -> f64 { if self.tp + self.fn_ == 0 { 1.0 } else { self.tp as f64 / (self.tp + self.fn_) as f64 } }
    pub fn false_alarm(&self) -> f64 { if self.fp + self.tn == 0 { 0.0 } else { self.fp as f64 / (self.fp + self.tn) as f64 } }
}
#[derive(Serialize, Deserialize, Clone, Debug)]
pub struct Results { pub thresholds: Thresholds, pub cases: Vec<Case>, pub scores: BTreeMap<String, Score> }

fn read(dir: &str, f: &str) -> anyhow::Result<String> { Ok(std::fs::read_to_string(Path::new(dir).join(f))?) }

pub fn run_all(dir: &str) -> anyhow::Result<Results> { run_with(dir, Thresholds::default()) }

pub fn run_with(dir: &str, t: Thresholds) -> anyhow::Result<Results> {
    let fx: Fixtures = serde_json::from_str(&read(dir, "cases.json")?)?;
    let cfg = |k: &str| fx.configs.iter().find(|c| c.key == k).cloned().ok_or_else(|| anyhow::anyhow!("no config {k}"));
    let mut cases = vec![];
    for p in &fx.real {
        let c = cfg(&p.config)?;
        let b = profile(&read(dir, &p.before)?, &c.fields);
        let a = profile(&read(dir, &p.after)?, &c.fields);
        cases.push(Case { set: "real".into(), config: c.key.clone(), before: p.before.clone(), after: p.after.clone(), mutation: "real".into(),
            label_break: p.label == "break", note: p.note.clone(), report: compare(&b, &a, &c.fields, t) });
    }
    for base in &fx.synthetic_bases {
        let c = cfg(&base.config)?;
        let html = read(dir, &base.file)?;
        let bp = profile(&html, &c.fields);
        for (names, label) in [(BREAKING, true), (BENIGN, false)] {
            for m in names.iter() {
                for &seed in &fx.seeds {
                    let Some(out) = apply(m, &html, &c.fields, seed) else { break };
                    let ap = profile(&out, &c.fields);
                    cases.push(Case { set: "synthetic".into(), config: c.key.clone(), before: base.file.clone(), after: format!("{m}#{seed}"), mutation: m.to_string(),
                        label_break: label, note: String::new(), report: compare(&bp, &ap, &c.fields, t) });
                    if !["text_edit", "ad_churn", "tracking_attrs", "script_churn"].contains(m) { break; } // deterministic ones need one seed
                }
            }
        }
    }
    let mut scores: BTreeMap<String, Score> = BTreeMap::new();
    for c in &cases {
        for (policy, pred) in [("any_alert", c.report.verdict >= Verdict::Warn), ("break_only", c.report.verdict == Verdict::Break)] {
            for set in [c.set.as_str(), "all"] {
                scores.entry(format!("{set}/{policy}")).or_default().add(c.label_break, pred);
            }
            scores.entry(format!("mutation/{}/{policy}", c.mutation)).or_default().add(c.label_break, pred);
        }
    }
    Ok(Results { thresholds: t, cases, scores })
}

pub fn write(r: &Results, dir: &str) -> anyhow::Result<()> {
    std::fs::create_dir_all(dir)?;
    std::fs::write(Path::new(dir).join("results.json"), serde_json::to_string_pretty(r)?)?;
    std::fs::write(Path::new(dir).join("RESULTS.md"), summary_md(r))?;
    Ok(())
}

fn pct(x: f64) -> String { format!("{:.0}%", x * 100.0) }
fn v(x: Verdict) -> &'static str { match x { Verdict::Ok => "ok", Verdict::Warn => "WARN", Verdict::Break => "BREAK" } }

pub fn summary_md(r: &Results) -> String {
    let mut s = String::from("# Replay results\n\nGenerated by `cargo run --release -- eval`. Positive = the extractor would break.\n`break_only` alerts on BREAK; `any_alert` also counts WARN (layout or container moved, selectors still work).\n\n| set | policy | cases | TP | FP | FN | TN | precision | recall | false alarms on benign |\n|---|---|---|---|---|---|---|---|---|---|\n");
    for set in ["real", "synthetic", "all"] {
        for pol in ["break_only", "any_alert"] {
            if let Some(x) = r.scores.get(&format!("{set}/{pol}")) {
                s += &format!("| {set} | {pol} | {} | {} | {} | {} | {} | {} | {} | {}/{} ({}) |\n", x.tp + x.fp + x.fn_ + x.tn, x.tp, x.fp, x.fn_, x.tn, pct(x.precision()), pct(x.recall()), x.fp, x.fp + x.tn, pct(x.false_alarm()));
            }
        }
    }
    s += "\n## Synthetic mutations\n\n| mutation | label | cases | BREAK | WARN only | ok |\n|---|---|---|---|---|---|\n";
    let mut names: Vec<(&str, bool)> = BREAKING.iter().map(|m| (*m, true)).chain(BENIGN.iter().map(|m| (*m, false))).collect();
    names.dedup();
    for (m, lab) in names {
        let cs: Vec<&Case> = r.cases.iter().filter(|c| c.mutation == m).collect();
        let n = |vv: Verdict| cs.iter().filter(|c| c.report.verdict == vv).count();
        s += &format!("| {m} | {} | {} | {} | {} | {} |\n", if lab { "breaking" } else { "benign" }, cs.len(), n(Verdict::Break), n(Verdict::Warn), n(Verdict::Ok));
    }
    s += "\n## Which signal fired (all cases)\n\n| signal | on breaking cases | on benign cases |\n|---|---|---|\n";
    for k in ["selector_died", "matches_dropped", "schema_drift", "values_collapsed", "field_moved", "layout_changed"] {
        let f = |lab: bool| r.cases.iter().filter(|c| c.label_break == lab && c.report.signals.iter().any(|x| x.kind == k)).count();
        let tot = |lab: bool| r.cases.iter().filter(|c| c.label_break == lab).count();
        s += &format!("| {k} | {}/{} | {}/{} |\n", f(true), tot(true), f(false), tot(false));
    }
    s += "\n## Real archived pairs (Wayback Machine snapshots)\n\n| config | before | after | hand label | verdict | shape sim | signals | note |\n|---|---|---|---|---|---|---|---|\n";
    for c in r.cases.iter().filter(|c| c.set == "real") {
        let sig: Vec<String> = c.report.signals.iter().map(|x| format!("{}{}", x.kind, x.field.as_ref().map(|f| format!("({f})")).unwrap_or_default())).collect();
        s += &format!("| {} | {} | {} | {} | {} | {:.2} | {} | {} |\n", c.config, c.before.rsplit('/').next().unwrap(), c.after.rsplit('/').next().unwrap(), if c.label_break { "break" } else { "benign" }, v(c.report.verdict), c.report.shape_similarity, if sig.is_empty() { "-".into() } else { sig.join(", ") }, c.note);
    }
    s
}
